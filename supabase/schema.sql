-- =====================================================================
-- Supplier Registration Status — Supabase schema
-- Run in Supabase Dashboard → SQL Editor → New query → Run.
-- Safe to re-run: every statement is idempotent.
-- =====================================================================

create extension if not exists "pgcrypto";

-- ---------------------------------------------------------------------
-- 1. Table
-- ---------------------------------------------------------------------
create table if not exists public.supplier_registrations (
  id                         uuid primary key default gen_random_uuid(),
  no                         integer generated by default as identity unique,
  institute                  text not null check (length(trim(institute)) between 1 and 120),
  payments_closing_date      date,
  applications_closing_date  date,
  application_mode           text check (application_mode is null or length(application_mode) <= 80),
  method_of_payment          text check (method_of_payment is null or length(method_of_payment) <= 80),
  registration_fee           numeric(12,2) not null default 0 check (registration_fee >= 0),
  other_charges              numeric(12,2) not null default 0 check (other_charges >= 0),
  application_sent_date      date,
  remarks                    text check (remarks is null or length(remarks) <= 1000),
  status                     text not null default 'Pending'
                             check (status in ('Complete', 'Pending', 'In Progress', 'Rejected')),
  created_at                 timestamptz not null default now(),
  updated_at                 timestamptz not null default now()
);

create index if not exists supplier_registrations_status_idx    on public.supplier_registrations (status);
create index if not exists supplier_registrations_institute_idx on public.supplier_registrations (institute);
create index if not exists supplier_registrations_sent_idx      on public.supplier_registrations (application_sent_date);

-- ---------------------------------------------------------------------
-- 2. Keep updated_at fresh on every UPDATE
-- ---------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_supplier_registrations_updated_at on public.supplier_registrations;
create trigger trg_supplier_registrations_updated_at
  before update on public.supplier_registrations
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------
-- 3. Row Level Security
--
-- The app uses the public anon key with no login, so these policies let
-- anyone who has the site URL read AND write. That matches the brief,
-- but it means the data is effectively public-editable.
--
-- To lock it down later: enable Supabase Auth, then replace "anon,
-- authenticated" with just "authenticated" in the write policies below.
-- ---------------------------------------------------------------------
alter table public.supplier_registrations enable row level security;

drop policy if exists "read registrations"   on public.supplier_registrations;
drop policy if exists "insert registrations" on public.supplier_registrations;
drop policy if exists "update registrations" on public.supplier_registrations;
drop policy if exists "delete registrations" on public.supplier_registrations;

create policy "read registrations"
  on public.supplier_registrations for select
  to anon, authenticated
  using (true);

create policy "insert registrations"
  on public.supplier_registrations for insert
  to anon, authenticated
  with check (true);

create policy "update registrations"
  on public.supplier_registrations for update
  to anon, authenticated
  using (true) with check (true);

create policy "delete registrations"
  on public.supplier_registrations for delete
  to anon, authenticated
  using (true);

-- ---------------------------------------------------------------------
-- 4. Realtime
-- REPLICA IDENTITY FULL makes UPDATE/DELETE events carry the full old row.
-- ---------------------------------------------------------------------
alter table public.supplier_registrations replica identity full;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'supplier_registrations'
  ) then
    alter publication supabase_realtime add table public.supplier_registrations;
  end if;
end $$;
